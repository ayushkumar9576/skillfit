@dataclass
class IntelligenceEvidence:
    """
    A single traceable piece of evidence supporting an intelligence claim.

    Every structured intelligence object (TechnologyIntelligence,
    CompetencyIntelligence, etc.) must carry at least one IntelligenceEvidence
    instance. This makes every claim fully explainable:

        "Why was Docker marked IMPLEMENTED?"
        → Because: IntelligenceEvidence(
                       source=IntelligenceSourceType.PROJECT,
                       source_id="E-commerce Platform",
                       section="projects",
                       line_reference=42,
                       quote="Containerized the application using Docker"
                   )

    Attributes:
        source: Domain origin — one of IntelligenceSourceType.
        source_id: The identifier of the specific project/internship/cert.
        section: The resume section (e.g. "projects", "experience") for debugging.
        line_reference: The original line number in the normalized resume text.
        quote: The verbatim or normalized excerpt from the resume.
    """
    source: IntelligenceSourceType
    source_id: str
    section: str
    quote: str
    line_reference: Optional[int] = None


