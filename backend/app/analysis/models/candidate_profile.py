@dataclass
class TechnologyIntelligence:
    """
    Intelligence record for a single technology observed in the resume.

    Aggregated across projects and internships. The aggregator merges duplicate
    technology entries and calculates the highest DemonstrationLevel observed.

    Attributes:
        technology: Normalized technology name.
        demonstration_level: Highest observed demonstration level (DemonstrationLevel value).
        evidence: All supporting evidence across sources.
        source_types: Unique IntelligenceSourceType values (as str) seen for this tech.
    """
    technology: str
    demonstration_level: str = DemonstrationLevel.CLAIMED.value
    evidence: List[IntelligenceEvidence] = field(default_factory=list)
    source_types: List[str] = field(default_factory=list)


@dataclass
class CompetencyIntelligence:
    """
    Intelligence record for a demonstrated engineering competency.

    The competency field must be a value from CompetencyType to enforce
    normalization. Different engines may produce competencies that map to the
    same canonical CompetencyType value; the aggregator merges them.

    Attributes:
        competency: Canonical competency name from CompetencyType.
        demonstrated: True if the evidence strongly supports the competency.
        demonstration_level: Depth of competency demonstration (DemonstrationLevel value).
        evidence: Supporting evidence across sources.
        supporting_technologies: Technologies that evidence this competency.
        supporting_projects: Project IDs that evidence this competency.
    """
    competency: str
    demonstrated: bool = False
    demonstration_level: str = DemonstrationLevel.CLAIMED.value
    evidence: List[IntelligenceEvidence] = field(default_factory=list)
    supporting_technologies: List[str] = field(default_factory=list)
    supporting_projects: List[str] = field(default_factory=list)


@dataclass
class SkillIntelligence:
    """
    Evidence-based intelligence record for a single skill.

    Verification status and evidence_count are computed deterministically by
    the Skill Verification Engine — never set by the LLM.

    Attributes:
        skill: Normalized skill name.
        verification_status: Computed verification level (VerificationStatus value).
        demonstration_level: Highest observed demonstration level.
        evidence: All supporting evidence instances.
        evidence_count: Number of distinct evidence items (used as confidence proxy).
    """
    skill: str
    verification_status: str = VerificationStatus.UNVERIFIED.value
    demonstration_level: str = DemonstrationLevel.CLAIMED.value
    evidence: List[IntelligenceEvidence] = field(default_factory=list)
    evidence_count: int = 0


@dataclass
class DomainIntelligence:
    """
    Intelligence record for a high-level technical domain.

    The domain field must be a value from DomainType to prevent string drift.

    Attributes:
        domain: Canonical domain label from DomainType.
        supporting_competencies: CompetencyType values that map to this domain.
        supporting_technologies: Technology names evidencing this domain.
        evidence: Supporting evidence.
    """
    domain: str
    supporting_competencies: List[str] = field(default_factory=list)
    supporting_technologies: List[str] = field(default_factory=list)
    evidence: List[IntelligenceEvidence] = field(default_factory=list)


@dataclass
class WorkplaceExposure:
    """
    A structured record of professional workplace exposure demonstrated during
    an internship (e.g., Agile, CI/CD, Production Systems, Code Reviews).

    Attributes:
        exposure_type: Normalized exposure label.
        evidence: Supporting evidence from internship descriptions.
    """
    exposure_type: str
    evidence: List[IntelligenceEvidence] = field(default_factory=list)


@dataclass
class EngineeringSignal:
    """
    A specific engineering practice or pattern detected in the resume.

    Signals are grouped by EngineeringSignalCategory and aggregated across
    all intelligence sources. Used for Project Tier scoring and Readiness.

    Attributes:
        category: Signal category value from EngineeringSignalCategory.
        signal: Human-readable signal description (e.g. "Docker deployment").
        demonstrated: True if the signal is backed by at least one evidence item.
        evidence: Supporting evidence.
    """
    category: str
    signal: str
    demonstrated: bool = False
    evidence: List[IntelligenceEvidence] = field(default_factory=list)


@dataclass
class OwnershipIntelligence:
    """
    A structured ownership signal extracted from projects or internships.

    Represents what the candidate individually built, led, or owned.

    Attributes:
        signal: Short description of what was owned (e.g. "Designed training pipeline").
        ownership_level: Ownership depth value from OwnershipLevel.
        evidence: Supporting evidence.
    """
    signal: str
    ownership_level: str = OwnershipLevel.CONTRIBUTED.value
    evidence: List[IntelligenceEvidence] = field(default_factory=list)


@dataclass
class Finding:
    """
    A qualitative finding generated by an intelligence engine.

    Covers STRENGTH, WEAKNESS, and MISSING_SIGNAL types.
    RECOMMENDATION is a separate class (Recommendation) because it has
    additional metadata (priority, target_competencies, etc.).

    Attributes:
        type: FindingType value.
        severity: FindingSeverity value.
        title: Short, human-readable title.
        description: Detailed explanation.
        evidence: Supporting evidence (empty for MISSING_SIGNAL).
    """
    type: str
    severity: str
    title: str
    description: str = ""
    evidence: List[IntelligenceEvidence] = field(default_factory=list)


@dataclass
class Recommendation:
    """
    An improvement recommendation derived deterministically from Findings.

    Generated by the Candidate Intelligence Aggregator — never by the LLM.
    Only generated when a WEAKNESS or MISSING_SIGNAL with severity >= HIGH exists.

    Attributes:
        title: Short, actionable recommendation.
        description: Detailed explanation of the recommended action.
        derived_from: List of Finding titles that triggered this recommendation.
        estimated_impact: Short description of expected career impact.
        priority: Relative priority (uses FindingSeverity values).
        target_competencies: CompetencyType values this recommendation develops.
    """
    title: str
    description: str = ""
    derived_from: List[str] = field(default_factory=list)
    estimated_impact: str = ""
    priority: str = FindingSeverity.MEDIUM.value
    target_competencies: List[str] = field(default_factory=list)


@dataclass
class ProjectSophisticationRecord:
    """
    Per-project sophistication assessment, persisted in the candidate profile.

    The ``sophistication_score`` (0–100) is produced by the LLM.
    The ``sophistication_tier`` is derived deterministically by the Python
    engine via ``score_to_tier()`` — never by the LLM.

    Attributes:
        project_name:           Title of the analyzed project.
        sophistication_score:   0–100 holistic project complexity score.
        sophistication_tier:    Canonical tier string (BEGINNER … INDUSTRY_GRADE).
        sophistication_reasoning: Concise LLM justification (≤ 30 words).
    """
    project_name: str
    sophistication_score: int
    sophistication_tier: str
    sophistication_reasoning: str = ""


@dataclass
class CertificationIntelligence:
    """
    Intelligence record for a professional certification.

    Captures what a certification actually signals to a hiring team —
    which competencies and domains it supports, and where its limitations
    are (e.g., a Cloud Practitioner cert indicates awareness but not implementation).

    Attributes:
        certification_name: Full certification title.
        category: Domain category (e.g. "Cloud", "Data Science", "Security").
        supported_competencies: CompetencyType values this cert validates.
        supported_domains: DomainType values this cert signals.
        industry_recognition: Qualitative recognition level (e.g. "high", "moderate").
        practical_strength: Whether the cert is theory-heavy or implementation-supporting.
        limitations: Explicit capability gaps the cert does NOT validate.
        evidence: Supporting resume evidence.
    """
    certification_name: str
    category: str = ""
    supported_competencies: List[str] = field(default_factory=list)
    supported_domains: List[str] = field(default_factory=list)
    industry_recognition: str = ""
    practical_strength: str = ""
    limitations: List[str] = field(default_factory=list)
    evidence: List[IntelligenceEvidence] = field(default_factory=list)


