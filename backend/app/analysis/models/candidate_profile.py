@dataclass
class CandidateSummary:
    """
    Deterministically derived dashboard summary layer.

    Generated by the Candidate Intelligence Aggregator from the full profile.
    Powers the candidate dashboard hero section and executive views.

    Attributes:
        primary_domains: Top 2-3 domains by evidence strength.
        strongest_competencies: Top competencies by evidence depth.
        strongest_technologies: Top technologies by demonstration level.
        largest_gaps: Missing signals with HIGH/CRITICAL severity.
        readiness_highlights: Positive summary bullets for the dashboard.
    """
    primary_domains: List[str] = field(default_factory=list)
    strongest_competencies: List[str] = field(default_factory=list)
    strongest_technologies: List[str] = field(default_factory=list)
    largest_gaps: List[str] = field(default_factory=list)
    readiness_highlights: List[str] = field(default_factory=list)


@dataclass
class CandidateIntelligenceProfile:
    """
    The canonical, unified intelligence model for a candidate.

    Pure domain model — contains no persistence metadata. Used in:
        - Phase 5 Matching Engine (no raw resume text access needed)
        - Phase 4 Readiness Engine
        - API responses (recruiter views, candidate dashboard)
        - Explainability queries
        - Regression tests

    All intelligence objects are fully evidence-backed. Every claim can be
    explained by tracing its evidence list.

    Design invariant:
        Every field that downstream systems need to derive readiness, do matching,
        generate recommendations, or answer explainability queries must live here.
        No system beyond the initial analysis stage should need raw resume text.
    """
    # Technology and skill intelligence
    technologies: List[TechnologyIntelligence] = field(default_factory=list)
    competencies: List[CompetencyIntelligence] = field(default_factory=list)
    domains: List[DomainIntelligence] = field(default_factory=list)
    skills: List[SkillIntelligence] = field(default_factory=list)
    certifications: List[CertificationIntelligence] = field(default_factory=list)

    # Engineering and workplace intelligence
    ownership_signals: List[OwnershipIntelligence] = field(default_factory=list)
    engineering_signals: List[EngineeringSignal] = field(default_factory=list)
    workplace_exposure: List[WorkplaceExposure] = field(default_factory=list)

    # Findings and recommendations
    findings: List[Finding] = field(default_factory=list)
    recommendations: List[Recommendation] = field(default_factory=list)

    # Project sophistication intelligence (Phase 3 enhancement)
    # Per-project records — populated by ProjectAnalysisEngine
    project_sophistication: List[ProjectSophisticationRecord] = field(default_factory=list)
    # Aggregate metrics — computed by CandidateIntelligenceAggregator
    average_project_sophistication: float = 0.0
    highest_project_sophistication: int = 0

    # Dashboard layer (derived, not set by engines directly)
    summary: CandidateSummary = field(default_factory=CandidateSummary)

    # Profile-level metadata (avoids downstream systems reading raw results)
    metadata: ProfileMetadata = field(default_factory=ProfileMetadata)


@dataclass
class CandidateIntelligenceSnapshot:
    """
    Persistence wrapper for the CandidateIntelligenceProfile.

    Separates domain logic (the profile) from persistence concerns (metadata).
    Stored as a versioned snapshot in the database. Regenerated whenever a
    new resume analysis runs.

    Attributes:
        snapshot_id: Unique snapshot identifier (UUID).
        resume_id: The source resume this snapshot was generated from.
        profile_version: Semantic schema version of the profile structure.
        analysis_version: Version of the analysis engine that produced the profile.
        generated_at: UTC timestamp of snapshot generation.
        profile: The actual CandidateIntelligenceProfile domain model.
    """
    snapshot_id: str
    resume_id: str
    profile_version: str
    analysis_version: str
    profile: CandidateIntelligenceProfile
    generated_at: datetime = field(default_factory=lambda: datetime.now(timezone.utc))
