"""
app/analysis/models/candidate_profile.py
-----------------------------------------
Canonical Candidate Intelligence Profile — the single unified intelligence
model for the SkillFit platform.

Design Rules:
    - Pure standard library dataclasses and enums only.
    - Zero framework dependencies (no SQLAlchemy, FastAPI, Pydantic, or OpenAI).
    - All intelligence is evidence-backed and traceable.
    - Fully serializable via dataclasses.asdict().

Separation of Concerns:
    - CandidateIntelligenceProfile  : pure domain model (used in matching, APIs, tests)
    - CandidateIntelligenceSnapshot : persistence wrapper (adds metadata for DB storage)

Consumed by:
    - Phase 3: All analysis engines (Projects, Internships, Certifications, Skills)
    - Phase 3: Candidate Intelligence Aggregator
    - Phase 4: Readiness Engine
    - Phase 5: Matching Engine
    - APIs: Recruiter Views, Candidate Dashboard
"""

from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime, timezone
from enum import Enum
from typing import List, Optional

from app.core.enums import CanonicalCompetencyType, ProfessionalDomainType

# ---------------------------------------------------------------------------
# Taxonomy Enums
# ---------------------------------------------------------------------------

class DemonstrationLevel(str, Enum):
    """
    Ordered scale of how concretely a candidate has demonstrated a
    technology or skill. Used across Projects, Internships, and Skills.

    Ordering (weakest → strongest):
        CLAIMED < REFERENCED < USED < IMPLEMENTED < DESIGNED < ARCHITECTED
    """
    CLAIMED = "CLAIMED"
    REFERENCED = "REFERENCED"
    USED = "USED"
    IMPLEMENTED = "IMPLEMENTED"
    DESIGNED = "DESIGNED"
    ARCHITECTED = "ARCHITECTED"

    @classmethod
    def rank(cls) -> dict:
        """Return ordinal mapping for comparison logic."""
        return {m: i for i, m in enumerate(cls)}


class OwnershipLevel(str, Enum):
    """
    Ordered scale of ownership and leadership depth demonstrated.
    Used in OwnershipIntelligence extracted from projects and internships.
    """
    OBSERVED = "OBSERVED"
    CONTRIBUTED = "CONTRIBUTED"
    IMPLEMENTED = "IMPLEMENTED"
    OWNED = "OWNED"
    LED = "LED"


class VerificationStatus(str, Enum):
    """
    Evidence-based verification confidence for a skill.
    Derived deterministically by the aggregator — never set by the LLM.

    Thresholds (based on SKILL_EVIDENCE_WEIGHTS):
        UNVERIFIED       — weighted score < 0.3
        WEAKLY_VERIFIED  — weighted score >= 0.3
        VERIFIED         — weighted score >= 1.0
        STRONGLY_VERIFIED — weighted score >= 2.0
    """
    UNVERIFIED = "UNVERIFIED"
    WEAKLY_VERIFIED = "WEAKLY_VERIFIED"
    VERIFIED = "VERIFIED"
    STRONGLY_VERIFIED = "STRONGLY_VERIFIED"


class FindingType(str, Enum):
    """Type of a qualitative finding generated by an intelligence engine."""
    STRENGTH = "STRENGTH"
    WEAKNESS = "WEAKNESS"
    MISSING_SIGNAL = "MISSING_SIGNAL"


class FindingSeverity(str, Enum):
    """
    Severity of a finding. Drives recommendation prioritization.
    HIGH/CRITICAL findings generate recommendations automatically.
    """
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


# ---------------------------------------------------------------------------
# Canonical Competency and Domain Taxonomy
#
# Both enums now live in app.core.enums and are shared across Candidate and
# Drive intelligence. Aliases below preserve backward compatibility for all
# engine code that imports CompetencyType / DomainType from this module.
# ---------------------------------------------------------------------------

# Canonical competency taxonomy (source of truth: app.core.enums)
CompetencyType = CanonicalCompetencyType

# Canonical domain taxonomy (source of truth: app.core.enums)
# Note: ProfessionalDomainType now includes both high-level business domains
# (AI_ML, SOFTWARE_ENGINEERING) and fine-grained technical domains (BACKEND,
# MACHINE_LEARNING) in a single unified taxonomy.
DomainType = ProfessionalDomainType



class EngineeringSignalCategory(str, Enum):
    """
    Canonical categories for engineering signal classification.
    Each category maps to a distinct set of hiring signals.
    """
    ARCHITECTURE = "ARCHITECTURE"
    DEPLOYMENT = "DEPLOYMENT"
    TESTING = "TESTING"
    SECURITY = "SECURITY"
    MONITORING = "MONITORING"
    INTEGRATION = "INTEGRATION"


class IntelligenceSourceType(str, Enum):
    """
    Canonical source types for intelligence evidence.

    Strongly typed to prevent silent string drift in the evidence weighting
    system. Every IntelligenceEvidence instance must declare its source using
    this enum — not a freeform string.

    Used by:
        - Skill Verification Engine (evidence weighting)
        - Explainability layer (source tracing)
        - Matching Engine (source credibility)
    """
    PROJECT = "project"
    INTERNSHIP = "internship"
    CERTIFICATION = "certification"
    SELF_REPORTED = "self_reported"


