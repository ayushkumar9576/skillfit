@dataclass
class ProfileMetadata:
    """
    Lightweight metadata about what was analyzed when generating this profile.

    Stored inside CandidateIntelligenceProfile so that downstream systems
    (Readiness Engine, Persistence Service, APIs) never need to read the
    raw ResumeAnalysis result to know how many projects/internships/certs
    were processed.

    Attributes:
        total_projects_analyzed:      Number of projects processed by the engine.
        total_internships_analyzed:   Number of internships processed.
        total_certifications_analyzed: Number of certifications processed.
        analysis_version:             Engine version string for reproducibility.
    """
    total_projects_analyzed: int = 0
    total_internships_analyzed: int = 0
    total_certifications_analyzed: int = 0
    analysis_version: str = ""


